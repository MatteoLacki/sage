//! Precursor-major fragment index: blocks of consecutive peptide rows, each split into
//! fragment m/z cells (necromerge2 `plans/fragment_grid.md`, `docs/ai/fragment_grid.md`).

use crate::database::{scan_masses, PeptideIx, Theoretical};
use crate::mass::Tolerance;
use rayon::prelude::*;
use std::cell::RefCell;
use std::ops::Range;

/// How `Parameters::build_from_peptides` lays out the fragment index.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum FragmentLayout {
    /// Fragment-mass pages, each sorted by peptide (sage's own).
    #[default]
    Pages,
    Grid(GridShape),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GridShape {
    pub rows_per_block: usize,
    /// Mantissa bits kept in a cell key: 2^cell_bits cells per octave of m/z.
    pub cell_bits: u32,
}

impl Default for GridShape {
    fn default() -> Self {
        GridShape {
            rows_per_block: 4096,
            cell_bits: 10,
        }
    }
}

impl FragmentLayout {
    /// `SAGE_FRAGMENT_LAYOUT=pages|grid`, with `SAGE_GRID_ROWS` and
    /// `SAGE_GRID_CELL_BITS` shaping the grid.
    pub fn from_environment() -> Self {
        match std::env::var("SAGE_FRAGMENT_LAYOUT").as_deref() {
            Err(_) | Ok("pages") => FragmentLayout::Pages,
            Ok("grid") => {
                let default = GridShape::default();
                let shape = GridShape {
                    rows_per_block: environment_number("SAGE_GRID_ROWS")
                        .unwrap_or(default.rows_per_block),
                    cell_bits: environment_number("SAGE_GRID_CELL_BITS")
                        .map(|bits| bits as u32)
                        .unwrap_or(default.cell_bits),
                };
                assert!(
                    shape.rows_per_block >= 1,
                    "SAGE_GRID_ROWS must be at least 1"
                );
                assert!(
                    shape.cell_bits <= 23,
                    "SAGE_GRID_CELL_BITS must be at most 23"
                );
                FragmentLayout::Grid(shape)
            }
            Ok(other) => panic!("SAGE_FRAGMENT_LAYOUT must be pages or grid, not {other}"),
        }
    }
}

fn environment_number(name: &str) -> Option<usize> {
    let value = std::env::var(name).ok()?;
    Some(
        value
            .parse()
            .unwrap_or_else(|_| panic!("{name} must be a whole number, not {value}")),
    )
}

/// Where each (block, cell) run of the fragment columns starts.
#[derive(Debug, Default)]
pub struct FragmentGrid {
    rows: usize,
    rows_per_block: usize,
    shift: u32,
    first_cell: u32,
    cells: usize,
    /// Fragment offset of each block's first fragment, plus the total.
    block_starts: Vec<usize>,
    /// Per block, `cells + 1` offsets relative to the block's first fragment.
    cell_starts: Vec<u32>,
}

/// Per-thread scratch for building and searching.
#[derive(Default)]
struct GridScratch {
    fragments: Vec<Theoretical>,
    cursors: Vec<u32>,
    /// One per searched window: its fragment bounds and the cells holding them.
    windows: Vec<(f32, f32, usize, usize)>,
}

thread_local! {
    static GRID_SCRATCH: RefCell<GridScratch> = RefCell::new(GridScratch::default());
}

impl FragmentGrid {
    /// Lay out the fragments of peptide rows `0..rows`, generated by `fragments_of(row,
    /// out)` in a fixed order, as a grid; returns it with the m/z and peptide columns.
    /// Each block is generated twice (count, then place), so nothing beyond the
    /// columns is held.
    pub fn build(
        rows: usize,
        shape: GridShape,
        fragments_of: impl Fn(usize, &mut Vec<Theoretical>) + Sync,
    ) -> (FragmentGrid, Vec<f32>, Vec<PeptideIx>) {
        let shift = 23 - shape.cell_bits;
        let blocks = (rows + shape.rows_per_block - 1) / shape.rows_per_block;
        let block_rows = |block: usize| {
            block * shape.rows_per_block..((block + 1) * shape.rows_per_block).min(rows)
        };
        let generate = |block: usize, out: &mut Vec<Theoretical>| {
            out.clear();
            for row in block_rows(block) {
                fragments_of(row, out);
            }
        };

        let census: Vec<(usize, u32, u32)> = (0..blocks)
            .into_par_iter()
            .map(|block| {
                GRID_SCRATCH.with(|scratch| {
                    let fragments = &mut scratch.borrow_mut().fragments;
                    generate(block, fragments);
                    let mut lowest = u32::MAX;
                    let mut highest = 0;
                    for fragment in fragments.iter() {
                        assert!(
                            fragment.fragment_mz > 0.0 && fragment.fragment_mz.is_finite(),
                            "fragment m/z {} cannot be placed in the grid",
                            fragment.fragment_mz
                        );
                        let key = fragment.fragment_mz.to_bits() >> shift;
                        lowest = lowest.min(key);
                        highest = highest.max(key);
                    }
                    (fragments.len(), lowest, highest)
                })
            })
            .collect();

        let first_cell = census
            .iter()
            .map(|&(_, lowest, _)| lowest)
            .min()
            .unwrap_or(0);
        let last_cell = census
            .iter()
            .map(|&(_, _, highest)| highest)
            .max()
            .unwrap_or(0);
        let cells = match census.iter().any(|&(count, _, _)| count > 0) {
            true => (last_cell - first_cell) as usize + 1,
            false => 0,
        };
        let mut block_starts = Vec::with_capacity(blocks + 1);
        block_starts.push(0);
        for &(count, _, _) in &census {
            assert!(
                count <= u32::MAX as usize,
                "a grid block holds too many fragments"
            );
            block_starts.push(block_starts.last().unwrap() + count);
        }
        let total = *block_starts.last().unwrap();

        let mut fragment_mzs = vec![0.0f32; total];
        let mut fragment_peptide_indices = vec![PeptideIx(0); total];
        let mut cell_starts = vec![0u32; blocks * (cells + 1)];
        let mzs_by_block = split_by_starts(&mut fragment_mzs, &block_starts);
        let ids_by_block = split_by_starts(&mut fragment_peptide_indices, &block_starts);
        mzs_by_block
            .into_par_iter()
            .zip(ids_by_block)
            .zip(cell_starts.par_chunks_mut(cells + 1))
            .enumerate()
            .for_each(|(block, ((mzs, ids), starts))| {
                GRID_SCRATCH.with(|scratch| {
                    let GridScratch {
                        fragments, cursors, ..
                    } = &mut *scratch.borrow_mut();
                    generate(block, fragments);
                    assert_eq!(fragments.len(), mzs.len(), "block {block} changed size");
                    let cell_of = |mz: f32| ((mz.to_bits() >> shift) - first_cell) as usize;
                    for fragment in fragments.iter() {
                        starts[cell_of(fragment.fragment_mz) + 1] += 1;
                    }
                    for cell in 1..starts.len() {
                        starts[cell] += starts[cell - 1];
                    }
                    cursors.clear();
                    cursors.extend_from_slice(starts);
                    for fragment in fragments.iter() {
                        let cursor = &mut cursors[cell_of(fragment.fragment_mz)];
                        mzs[*cursor as usize] = fragment.fragment_mz;
                        ids[*cursor as usize] = fragment.peptide_index;
                        *cursor += 1;
                    }
                });
            });

        let grid = FragmentGrid {
            rows,
            rows_per_block: shape.rows_per_block,
            shift,
            first_cell,
            cells,
            block_starts,
            cell_starts,
        };
        (grid, fragment_mzs, fragment_peptide_indices)
    }

    pub fn describe(&self) -> String {
        format!(
            "{} blocks of {} rows x {} cells ({} bits), directory {:.1} MB",
            self.block_starts.len() - 1,
            self.rows_per_block,
            self.cells,
            23 - self.shift,
            (self.cell_starts.len() * std::mem::size_of::<u32>()) as f64 / 1e6
        )
    }

    /// The cells holding every fragment with `lo <= m/z <= hi`; `None` when none can.
    fn cells_between(&self, lo: f32, hi: f32) -> Option<(usize, usize)> {
        let window_can_hold_a_fragment = hi >= lo && hi > 0.0;
        if self.cells == 0 || !window_can_hold_a_fragment {
            return None;
        }
        let last_cell = self.first_cell + (self.cells - 1) as u32;
        let lo_key = match lo > 0.0 {
            true => lo.to_bits() >> self.shift,
            false => 0,
        };
        let hi_key = hi.to_bits() >> self.shift;
        if hi_key < self.first_cell || lo_key > last_cell {
            return None;
        }
        Some((
            (lo_key.max(self.first_cell) - self.first_cell) as usize,
            (hi_key.min(last_cell) - self.first_cell) as usize,
        ))
    }

    /// Every fragment of a peptide in `candidates` falling in one of `windows`, once per
    /// window it falls in: the same matches `page_search_batch` finds in pages.
    pub fn search(
        &self,
        fragment_mzs: &[f32],
        fragment_peptide_indices: &[PeptideIx],
        candidates: Range<usize>,
        windows: &[(f32, Tolerance)],
        mut on_match: impl FnMut(Theoretical),
    ) {
        let candidates = candidates.start..candidates.end.min(self.rows);
        if candidates.is_empty() {
            return;
        }
        GRID_SCRATCH.with(|scratch| {
            let searched = &mut scratch.borrow_mut().windows;
            searched.clear();
            for &(mass, tolerance) in windows {
                let (lo, hi) = tolerance.theoretical_range(mass);
                if let Some((first, last)) = self.cells_between(lo, hi) {
                    searched.push((lo, hi, first, last));
                }
            }

            let first_block = candidates.start / self.rows_per_block;
            let last_block = (candidates.end - 1) / self.rows_per_block;
            for block in first_block..=last_block {
                let block_rows =
                    block * self.rows_per_block..((block + 1) * self.rows_per_block).min(self.rows);
                let all_candidates =
                    candidates.start <= block_rows.start && block_rows.end <= candidates.end;
                let block_start = self.block_starts[block];
                let starts = &self.cell_starts[block * (self.cells + 1)..][..self.cells + 1];
                for &(lo, hi, first, last) in searched.iter() {
                    let run = block_start + starts[first] as usize
                        ..block_start + starts[last + 1] as usize;
                    let masses = &fragment_mzs[run.clone()];
                    let ids = &fragment_peptide_indices[run];
                    scan_masses(masses, lo, hi, |i| {
                        let peptide = ids[i];
                        if all_candidates || candidates.contains(&(peptide.0 as usize)) {
                            on_match(Theoretical {
                                peptide_index: peptide,
                                fragment_mz: masses[i],
                            });
                        }
                    });
                }
            }
        });
    }
}

/// `values` cut at `starts` (ascending, first 0, last `values.len()`).
fn split_by_starts<'a, T>(mut values: &'a mut [T], starts: &[usize]) -> Vec<&'a mut [T]> {
    let mut pieces = Vec::with_capacity(starts.len().saturating_sub(1));
    for bounds in starts.windows(2) {
        let (piece, rest) = values.split_at_mut(bounds[1] - bounds[0]);
        pieces.push(piece);
        values = rest;
    }
    pieces
}
